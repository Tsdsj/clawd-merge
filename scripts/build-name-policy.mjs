// Offline build; --source checks an upstream checkout against the pinned hashes.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
const root = new URL("../leaderboard/data/name-policy/", import.meta.url);
const data = JSON.parse(readFileSync(new URL("selection.json", root), "utf8"));
const sources = JSON.parse(readFileSync(new URL("sources.json", root), "utf8"));
const digest = (value) => createHash("sha256").update(value).digest("hex");
const sourceIndex = process.argv.indexOf("--source");
if (sourceIndex !== -1) {
  const source = process.argv[sourceIndex + 1];
  if (!source) throw Error("--source needs a path");
  for (const [file, entry] of Object.entries(sources.files))
    if (
      digest(readFileSync(join(source, "src/main/resources", file))) !==
      entry.sha256
    )
      throw Error("Pinned source checksum mismatch: " + file);
  if (
    digest(readFileSync(join(source, "LICENSE.txt"))) !== sources.licenseSha256
  )
    throw Error("Pinned license checksum mismatch");
  for (const rule of data.base) {
    const words = new Set(
      readFileSync(
        join(source, "src/main/resources", rule.source),
        "utf8",
      ).split(/\r?\n/),
    );
    if (!words.has(rule.term))
      throw Error("Selected entry absent from pinned source: " + rule.id);
  }
}
const serialized = JSON.stringify(data);
const output =
  "// Generated by scripts/build-name-policy.mjs. Edit name-policy/selection.json.\n" +
  `export const data = ${JSON.stringify(data, null, 2)};\nexport const sha256 = '${digest(serialized)}';\n`;
const destination = new URL(
  "../leaderboard/data/name-policy-v1.js",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output)
    throw Error("Name-policy bundle is stale");
} else writeFileSync(destination, output);
console.log(
  `Name policy ${data.version}: ${data.base.length} base rules, ${data.project.length} project rules; bundle verified`,
);
